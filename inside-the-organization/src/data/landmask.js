const BBOX = POLYS.map((p) => {
  let a = 1e9, b = -1e9, c = 1e9, d = -1e9;
  for (const [x, y] of p) { a = Math.min(a, x); b = Math.max(b, x); c = Math.min(c, y); d = Math.max(d, y); }
  return [a, b, c, d];
});

function inPoly(poly, x, y) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

/** true si (lon, lat) est sur une terre émergée (ou l'Antarctique). */
export function isLand(lon, lat) {
  if (lat < -70) return true; // Antarctique
  for (let k = 0; k < POLYS.length; k++) {
    const b = BBOX[k];
    if (lon < b[0] || lon > b[1] || lat < b[2] || lat > b[3]) continue;
    if (inPoly(POLYS[k], lon, lat)) return true;
  }
  return false;
}
